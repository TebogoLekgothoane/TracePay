/** Hunter / catalog domains → brand id when a Simple Icon exists. */
export const DOMAIN_TO_BRAND_ID: Record<string, string> = Object.fromEntries(
  Object.entries(BRAND_DOMAINS).flatMap(([brandId, domains]) =>
    domains.map((domain) => [domain, brandId] as const),
  ),
);

export function resolveBrandIcon(
  brandIdOrDomain: string | null | undefined,
): SimpleIcon | null {
  const key = brandIdOrDomain?.trim().toLowerCase();
  if (!key) return null;

  if (BRAND_ICONS[key]) return BRAND_ICONS[key];

  const fromDomain = DOMAIN_TO_BRAND_ID[key];
  if (fromDomain && BRAND_ICONS[fromDomain]) {
    return BRAND_ICONS[fromDomain];
  }

  return null;
}

export function brandHex(icon: SimpleIcon): string {
  return `#${icon.hex}`;
}

/** True for glyph colours that vanish on a dark card (Cursor, X, GitHub, …). */
export function isDarkBrandColor(icon: SimpleIcon): boolean {
  const value = Number.parseInt(icon.hex, 16);
  const red = (value >> 16) & 0xff;
  const green = (value >> 8) & 0xff;
  const blue = value & 0xff;
  return (0.299 * red + 0.587 * green + 0.114 * blue) / 255 < 0.25;
}
